extension TranslateX on BuildContext {
  /// Looks up [key] in the current app language. Reading the locale here
  /// makes the widget rebuild automatically when the language changes.
  String tr(String key, [Map<String, String>? args]) =>
      Strings.of(Localizations.localeOf(this).languageCode, key, args);
}

/// "6h 30m" / "6 گھنٹے 30 منٹ" etc.
String formatDuration(String lang, Duration d) {
  final total = d.inMinutes < 0 ? 0 : d.inMinutes;
  final h = total ~/ 60;
  final m = total % 60;
  if (h > 0) {
    return Strings.of(lang, 'duration_hm', {'h': '$h', 'm': '$m'});
  }
  return Strings.of(lang, 'duration_m', {'m': '$m'});
}
